TEST_P(MatMatProtTest, SecMoECipherCipherSingleBlock) {
  // SecMoE uses a 64-bit arithmetic ring with
  // fixed-point precision 18 in the paper experiments.
  if (field_ != FieldType::FM64) {
    GTEST_SKIP() << "SecMoE CT-CT feasibility test targets FM64";
  }

  // Use one encoded block first:
  //
  //   [1 x 4] * [4 x 1] -> [1 x 1]
  //
  // This isolates ciphertext-ciphertext multiplication
  // from multi-block accumulation and ciphertext packing.
  MatMatProtocol::Meta meta;
  meta.dims = {1, 4, 1};

  auto lhs = ring_zeros(
      field_,
      {meta.dims[0], meta.dims[1]});

  auto rhs = ring_zeros(
      field_,
      {meta.dims[1], meta.dims[2]});

  // Deterministic small values avoid modular wraparound:
  //
  //   [1, 2, 3, 4] * [5, 6, 7, 8]^T = 70
  {
    auto lhs_view = NdArrayView<uint64_t>(lhs);
    lhs_view[0] = 1;
    lhs_view[1] = 2;
    lhs_view[2] = 3;
    lhs_view[3] = 4;

    auto rhs_view = NdArrayView<uint64_t>(rhs);
    rhs_view[0] = 5;
    rhs_view[1] = 6;
    rhs_view[2] = 7;
    rhs_view[3] = 8;
  }

  MatMatProtocol matmat_prot(
      *context_,
      *ms_helper_);

  const size_t lhs_n =
      matmat_prot.GetLeftSize(meta);

  const size_t rhs_n =
      matmat_prot.GetRightSize(meta);

  const size_t out_n =
      matmat_prot.GetOutSize(meta);

  // The selected dimensions should fit in one block.
  ASSERT_EQ(lhs_n, 1U);
  ASSERT_EQ(rhs_n, 1U);
  ASSERT_EQ(out_n, 1U);

  std::vector<RLWEPt> lhs_poly(lhs_n);
  std::vector<RLWEPt> rhs_poly(rhs_n);

  // Exactly one side carries Delta.
  //
  // Enc(Forward(Delta * A)) *
  // Enc(Backward(B))
  //
  // decrypts to a polynomial encoding Delta * A * B,
  // which is compatible with the existing ParseResult
  // and H2A conventions.
  matmat_prot.EncodeLHS(
      lhs,
      meta,
      true,
      absl::MakeSpan(lhs_poly));

  matmat_prot.EncodeRHS(
      rhs,
      meta,
      false,
      absl::MakeSpan(rhs_poly));

  seal::Encryptor encryptor(
      *context_,
      *rlwe_sk_);

  std::vector<RLWECt> lhs_ct(lhs_n);
  std::vector<RLWECt> rhs_ct(rhs_n);

  for (size_t i = 0; i < lhs_n; ++i) {
    NttInplace(
        lhs_poly[i],
        *context_);

    encryptor.encrypt_symmetric(
        lhs_poly[i],
        lhs_ct[i]);
  }

  for (size_t i = 0; i < rhs_n; ++i) {
    NttInplace(
        rhs_poly[i],
        *context_);

    encryptor.encrypt_symmetric(
        rhs_poly[i],
        rhs_ct[i]);
  }

  // Fresh RLWE ciphertexts normally contain two
  // polynomial components.
  ASSERT_EQ(lhs_ct[0].size(), 2U);
  ASSERT_EQ(rhs_ct[0].size(), 2U);
  ASSERT_TRUE(lhs_ct[0].is_ntt_form());
  ASSERT_TRUE(rhs_ct[0].is_ntt_form());
  ASSERT_EQ(
      lhs_ct[0].parms_id(),
      rhs_ct[0].parms_id());

  seal::Evaluator evaluator(
      *context_);

  std::vector<RLWECt> output_ct(out_n);

  // The operation missing from the existing public
  // MatMatProtocol interface:
  //
  //       ciphertext * ciphertext
  evaluator.multiply(
      lhs_ct[0],
      rhs_ct[0],
      output_ct[0]);

  // A multiplication of two size-2 ciphertexts produces
  // a size-3 ciphertext when no relinearization is used.
  EXPECT_EQ(
      output_ct[0].size(),
      3U);

  EXPECT_TRUE(
      output_ct[0].is_ntt_form());

  EXPECT_EQ(
      output_ct[0].parms_id(),
      lhs_ct[0].parms_id());

  // Protocol 1 immediately masks and decrypts every
  // ciphertext-ciphertext result. Therefore, first verify
  // that the secret key can directly decrypt size=3.
  seal::Decryptor decryptor(
      *context_,
      *rlwe_sk_);

  std::vector<RLWEPt> output_poly(out_n);

  decryptor.decrypt(
      output_ct[0],
      output_poly[0]);

  InvNttInplace(
      output_poly[0],
      *context_);

  auto computed = matmat_prot.ParseResult(
      field_,
      meta,
      absl::MakeSpan(output_poly));

  auto expected = ring_mmul(
      lhs,
      rhs);

  ASSERT_EQ(
      computed.numel(),
      expected.numel());

  auto computed_view =
      NdArrayView<uint64_t>(computed);

  auto expected_view =
      NdArrayView<uint64_t>(expected);

  ASSERT_EQ(
      expected_view[0],
      70U);

  // Distance over the ring Z_(2^64). This also handles
  // a small negative error represented near UINT64_MAX.
  const uint64_t forward_difference =
      computed_view[0] - expected_view[0];

  const uint64_t backward_difference =
      expected_view[0] - computed_view[0];

  const uint64_t difference =
      forward_difference < backward_difference
          ? forward_difference
          : backward_difference;

  // BumbleBee's ring-to-RLWE conversion can introduce
  // an approximation error of at most one ring unit.
  std::cout
      << "SECMOE_CTCT_ERROR"
      << " computed=" << computed_view[0]
      << " expected=" << expected_view[0]
      << " raw_difference=" << difference
      << " ciphertext_size=" << output_ct[0].size()
      << " ciphertext_scale=" << output_ct[0].scale()
      << std::endl;


  // -------------------------------------------------------
  // Minimal relinearization diagnostic.
  //
  // One ciphertext times one ciphertext:
  //
  // size 3 ciphertext
  // -> relinearize to size 2
  // -> direct decryption
  //
  // No multi-block accumulation and no H2A.
  // -------------------------------------------------------

  ASSERT_NE(relin_keys_, nullptr);

  RLWECt relinearized_ciphertext =
      output_ct[0];

  ASSERT_EQ(
      relinearized_ciphertext.size(),
      3U);

  ASSERT_TRUE(
      relinearized_ciphertext.is_ntt_form());

  seal::Evaluator relinearization_evaluator(
      *context_);

  relinearization_evaluator.relinearize_inplace(
      relinearized_ciphertext,
      *relin_keys_);

  ASSERT_EQ(
      relinearized_ciphertext.size(),
      2U);

  ASSERT_TRUE(
      relinearized_ciphertext.is_ntt_form());

  std::vector<RLWEPt>
      relinearized_output_poly(1);

  decryptor.decrypt(
      relinearized_ciphertext,
      relinearized_output_poly[0]);

  InvNttInplace(
      relinearized_output_poly[0],
      *context_);

  auto relinearized_computed =
      matmat_prot.ParseResult(
          field_,
          meta,
          absl::MakeSpan(
              relinearized_output_poly));

  ASSERT_EQ(
      relinearized_computed.numel(),
      expected.numel());

  auto relinearized_view =
      NdArrayView<uint64_t>(
          relinearized_computed);

  const uint64_t relin_forward =
      relinearized_view[0]
      - expected_view[0];

  const uint64_t relin_backward =
      expected_view[0]
      - relinearized_view[0];

  const uint64_t relin_difference =
      relin_forward < relin_backward
          ? relin_forward
          : relin_backward;

  std::cout
      << "SECMOE_CTCT_SINGLE_RELIN"
      << " computed="
      << relinearized_view[0]
      << " expected="
      << expected_view[0]
      << " raw_difference="
      << relin_difference
      << " ciphertext_size="
      << relinearized_ciphertext.size()
      << " ciphertext_moduli="
      << relinearized_ciphertext
             .coeff_modulus_size()
      << " ciphertext_scale="
      << relinearized_ciphertext.scale()
      << std::endl;

  // Temporary catastrophic-error guard.
  EXPECT_LE(
      relin_difference,
      65536U);

  // Temporary diagnostic cap. This is not yet the final
  // numerical tolerance for the SecMoE implementation.
  // The 64-ring-unit bound is based on the 100-run
  // single-block feasibility experiment:
  //
  // maximum observed error = 46
  // 64 / 2^18 = 2.44140625e-4
  EXPECT_LE(
      difference,
      64U)
      << "computed=" << computed_view[0]
      << ", expected=" << expected_view[0]
      << ", raw_difference=" << difference
      << ", ciphertext_size=" << output_ct[0].size()
      << ", ciphertext_scale=" << output_ct[0].scale();
}

